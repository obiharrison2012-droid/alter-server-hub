-- Altar Server Hub: shared quiz results table for Supabase
-- Run this in Supabase SQL Editor while signed into your own project.

create table if not exists public.quiz_results (
  id bigint generated by default as identity primary key,
  nickname text not null check (char_length(trim(nickname)) between 1 and 30),
  score integer not null check (score >= 0 and score <= 10),
  total_questions integer not null check (total_questions = 10),
  percentage integer not null check (percentage >= 0 and percentage <= 100),
  submitted_at timestamptz not null default now()
);

alter table public.quiz_results enable row level security;

-- Allow public website visitors to submit results only.
drop policy if exists "Anyone can submit valid quiz results" on public.quiz_results;
create policy "Anyone can submit valid quiz results"
  on public.quiz_results
  for insert
  to anon, authenticated
  with check (
    char_length(trim(nickname)) between 1 and 30
    and score between 0 and 10
    and total_questions = 10
    and percentage between 0 and 100
  );

-- Intentionally do not add a SELECT policy: public visitors cannot read other players' results.
-- The project owner can view rows in the Supabase dashboard's Table Editor.
